#!/usr/bin/env python3
"""Generate docs/API.md from neezy_backend docstrings (roadmap #78)."""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
BACKEND = ROOT / "neezy_backend"
OUTPUT = ROOT / "docs" / "API.md"


def _module_docstring(path: Path) -> str:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except Exception:
        return ""
    doc = ast.get_docstring(tree)
    if not doc:
        return ""
    first = doc.strip().splitlines()[0]
    return first[:160]


def _collect() -> list[tuple[str, str]]:
    mods: list[tuple[str, str]] = []
    for py in sorted(BACKEND.glob("*.py")):
        if py.name.startswith("_"):
            continue
        mods.append((py.stem, _module_docstring(py)))
    # also cli subpackage
    cli_dir = BACKEND / "cli"
    if cli_dir.exists():
        for py in sorted(cli_dir.glob("*.py")):
            if py.name.startswith("_"):
                continue
            mods.append((f"cli/{py.stem}", _module_docstring(py)))
    return mods


def build() -> str:
    mods = _collect()
    lines = [
        "# NEEZY Backend API — auto-generated (roadmap #78)",
        "",
        "> Generated by `python scripts/gen_api_docs.py`. Do not edit by hand; edit source docstrings.",
        "",
        f"**Modules:** {len(mods)} | **Source:** `neezy_backend/`",
        "",
        "| Module | Summary |",
        "|--------|---------|",
    ]
    for name, doc in mods:
        summary = doc.replace("|", "\\|") if doc else "—"
        lines.append(f"| `{name}` | {summary} |")
    lines += [
        "",
        "## CLI",
        "",
        "The CLI is `neezy_backend.cli:main` (`neezy-cli`). See `neezy-cli --help` for all subcommands:",
        "",
        "```",
        "neezy-cli capabilities --json    # version + capability flags (roadmap #32)",
        "neezy-cli watchlist show         # current watchlist",
        "neezy-cli watchlist export --file wl.json",
        "neezy-cli watchlist import --file wl.json",
        "neezy-cli markets --json",
        "neezy-cli doctor",
        "```",
        "",
        "## Notifiers (roadmap #13)",
        "",
        "- `neezy_backend.notifiers.Notifier` protocol",
        "- `TelegramNotifier`, `WebhookNotifier`, `MemoryNotifier`, `CompositeNotifier`",
        "",
        "## Snapshots (roadmap #24)",
        "",
        "- `neezy_backend.snapshots.capture_snapshot()` — pure helper",
        "- `neezy_backend.watchlists.export_watchlist()` / `import_watchlist()`",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/API.md")
    parser.add_argument(
        "--check", action="store_true", help="fail if output would change"
    )
    args = parser.parse_args(argv)
    content = build()
    if args.check:
        existing = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if existing != content:
            sys.stderr.write(
                "docs/API.md is stale — run `python scripts/gen_api_docs.py`\n"
            )
            return 1
        print("docs/API.md is fresh")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
